import React from 'react';
import type { TablerIcon } from '@tabler/icons-react';

/**
 * Иконка системы (03.09.2026).
 *
 * Зачем обёртка, если семейство и так одно (@tabler/icons-react):
 *
 * 1. Размеров в коде было четырнадцать — от 10 до 28, причём соседние
 *    (15, 16, 17) отличались на пиксель и читались как небрежность.
 *    Здесь их три, и других тип просто не даст поставить.
 * 2. Из 42 svg на экране aria-hidden стоял ровно у одного. Иконка рядом
 *    со словом «Просрочено» диктору не нужна — он уже прочитал слово, а
 *    вместо этого получал «graphic» посреди фразы. Теперь по умолчанию
 *    иконка скрыта от дерева доступности, а если она несёт смысл сама
 *    (стоит без подписи) — ей передают `label`, и она становится
 *    полноценной картинкой с именем.
 *
 * Толщину штриха не задаём: у tabler она 2 по умолчанию, и 284 иконки
 * из 290 её и использовали — расходились только шесть.
 */

/** 16 — в строках и пилюлях, 20 — кнопки и меню, 24 — крупные акценты */
export type IconSize = 16 | 20 | 24;

export interface IconProps extends Omit<React.ComponentPropsWithoutRef<'svg'>, 'ref'> {
  /** Сам компонент иконки: `<Icon icon={IconTruck} />` */
  icon: TablerIcon;
  size?: IconSize;
  /**
   * Имя иконки для экранного диктора. Ставится ТОЛЬКО когда иконка
   * стоит без текста и сама что-то значит. Рядом с подписью — не надо:
   * диктор прочитает её дважды.
   */
  label?: string;
}

export function Icon({ icon: Glyph, size = 16, label, ...rest }: IconProps) {
  if (label) {
    return <Glyph size={size} role="img" aria-label={label} {...rest} />;
  }
  return <Glyph size={size} aria-hidden focusable={false} {...rest} />;
}
