package nkt

import "testing"

func TestNormalizeGTIN(t *testing.T) {
	cases := []struct {
		in    string
		out   string
		valid bool
		why   string
	}{
		{"4870206710012", "4870206710012", true, "EAN-13 казахстанского префикса"},
		{"5449000000996", "5449000000996", true, "EAN-13"},
		{"96385074", "96385074", true, "EAN-8"},
		{"614141000036", "614141000036", true, "UPC-A"},
		{"10614141000033", "10614141000033", true, "ITF-14"},
		{" 5449000000996 ", "5449000000996", true, "пробелы из выгрузки отбрасываются"},
		{"5449-0000-00996", "5449000000996", true, "дефисы отбрасываются"},

		{"5449000000997", "", false, "битая контрольная цифра"},
		{"544900000099", "", false, "12 цифр, но контрольная не сходится"},
		{"54490000009", "", false, "недопустимая длина"},
		{"", "", false, "пусто"},
		{"нет", "", false, "текст вместо цифр"},
		{"5449000000О96", "", false, "кириллическая О вместо нуля"},
	}
	for _, c := range cases {
		got, ok := NormalizeGTIN(c.in)
		if got != c.out || ok != c.valid {
			t.Errorf("NormalizeGTIN(%q) = (%q, %v), ожидалось (%q, %v) — %s",
				c.in, got, ok, c.out, c.valid, c.why)
		}
	}
}
