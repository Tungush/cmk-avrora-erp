-- Индекс под расчёт отгрузки по актам (04.09.2026, найдено прогоном /review).
--
-- Зачем. Отгрузка позиции заказа больше не берётся из колонки
-- order_lines.shipped_qty — она была заполнена у 2 строк из 1814. Теперь
-- она считается по строкам актов, которые ищутся парой
-- «номер заказа + артикул». В таблице acceptance_act_lines был только
-- индекс по act_id, поэтому база прочёсывала все её строки на КАЖДУЮ
-- позицию заказа.
--
-- Замер на боевых данных до индекса: страница реестра (125 позиций)
-- 23 мс — терпимо; все 1814 позиций — 607 мс. Актов сегодня 228, они
-- копятся с каждой отгрузкой, и время растёт вместе с ними.
--
-- Порядок колонок именно такой: order_number идёт первым, потому что по
-- нему выполняется соединение с заказами, а article_id доотбирает уже
-- внутри найденного заказа.
--
-- CONCURRENTLY не используется намеренно: Prisma выполняет миграции в
-- транзакции, а CREATE INDEX CONCURRENTLY в транзакции запрещён. Таблица
-- маленькая (1282 строки), блокировка на запись будет мгновенной.
CREATE INDEX IF NOT EXISTS "acceptance_act_lines_order_number_article_id_idx"
  ON "acceptance_act_lines" ("order_number", "article_id");
